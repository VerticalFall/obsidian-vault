# 重算区间：低估线=max(悲观价值, 中枢×(1-MOS))；高估线=min(乐观价值, 中枢×(1+MOS))
for r in rows:
    r["extreme_low"] = r["bear_val"]
    r["extreme_high"] = r["bull_val"]
    r["low_line"] = round(max(r["bear_val"], r["base_val"] * (1 - r["mos"])))
    r["high_line"] = round(min(r["bull_val"], r["base_val"] * (1 + r["mos"])))
    r["pos_vs_base"] = round((r["level"] / r["base_val"] - 1) * 100, 1)
    if r["level"] < r["low_line"]:
        r["verdict"] = "低估区"
    elif r["level"] > r["high_line"]:
        r["verdict"] = "高估区"
    elif r["level"] < r["base_val"]:
        r["verdict"] = "合理区偏下"
    else:
        r["verdict"] = "合理区偏上"
    r["ey"] = round(100 / r["pe"], 2)
    r["erp"] = round(r["ey"] - r["rf"], 2)

