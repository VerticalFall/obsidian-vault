def calc_verdict(level, base, low, high):
    if level < low:
        return "低估区"
    if level > high:
        return "高估区"
    return "合理区偏下" if level < base else "合理区偏上"

for r in rows:
    m = MARKET[r["k"]]
    r["market"] = m[0]
    r["liq_score"], r["pricing_score"], r["policy_score"], r["governance_score"] = m[1], m[2], m[3], m[4]
    r["struct_score"] = round((m[1] + m[2] + m[3] + m[4]) / 4, 2)
    r["struct_discount"] = m[5]
    if m[5] == 0:
        r["base_val_adj"] = r["base_val"]
        r["low_line_adj"] = r["low_line"]
        r["high_line_adj"] = r["high_line"]
        r["verdict_adj"] = r["verdict"]
    else:
        r["base_val_adj"] = round(r["base_val"] * (1 - m[5]))
        ratio = 0.8 if r["k"] == "hsi" else 0.7
        r["low_line_adj"] = round(max(r["bear_val"], r["base_val_adj"] * ratio))
        r["high_line_adj"] = round(min(r["bull_val"], r["base_val_adj"] * (1.2 if r["k"] == "hsi" else 1.3)))
        r["verdict_adj"] = calc_verdict(r["level"], r["base_val_adj"], r["low_line_adj"], r["high_line_adj"])
    if r["k"] == "hstech":
        eps_cons = r["eps"] * 1.15
        r["eps_growth_cons"] = 15.0
        r["base_val_cons"] = round(eps_cons * r["band"][1])
        r["base_val_cons_adj"] = round(r["base_val_cons"] * (1 - r["struct_discount"]))

json.dump(rows, open(f"{BASE}/_data/index_valuation_model.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
